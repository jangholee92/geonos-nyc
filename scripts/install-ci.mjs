import {spawnSync} from 'node:child_process';
import {accessSync,constants} from 'node:fs';
import path from 'node:path';
import {projectRoot} from './runtime-env.mjs';
if(!process.env.npm_execpath)throw Error('Run this installer with npm run install:ci.');
process.env.SHARP_IGNORE_GLOBAL_LIBVIPS??='1';
const result=spawnSync(process.execPath,[process.env.npm_execpath,'ci','--prefix',projectRoot,'--workspaces=false','--include=dev','--include=optional','--no-audit','--no-fund'],{stdio:'inherit'});
if(result.error)throw result.error;
if(result.status!==0)process.exit(result.status??1);
accessSync(path.join(projectRoot,'node_modules','.bin',process.platform==='win32'?'vinext.cmd':'vinext'),process.platform==='win32'?constants.F_OK:constants.X_OK);
